#
# vru_basic_service.py
#
# Python porting of the VRU Basic Service, based on the C++ implementation in
# VaN3Twin and OScar (ETSI TS 103 300-3) - see https://github.com/DriveX-devs
#
# The service receives the kinematic status of the ego VRU via
# set_ego_vru_kstatus() (called by other services). It then checks the VAM
# triggering conditions (heading change, position change, speed change, safe
# distances, maximum elapsed time) either periodically every 100 ms or when
# externally triggered via a localhost UDP packet containing the string
# "check" — the mode is selected by the global flag DEFAULT_CHECK_MODE
# (periodic by default). VAMs are generated and UPER-encoded via asn1tools
# using the ASN.1 specifications ETSI-ITS-CDD and VAM-PDU-Description which
# must be available in the directory on this Python file.
#
# If the global flag PROXIMITY_CHECK_ENABLED is True (default), the LDM module
# is imported and the proximity checking ("SAFE DISTANCES" triggering condition
# of the C++ code) is performed by reading the LDM content.
#
# Statistics on the generated VAMs can be collected in a CSV file (one row per
# transmitted VAM) by attaching a VamStatsRecorder to the service through
# set_vam_stats(); a single recorder can be shared by all the VRU Basic
# Services of a scenario, so that it also reports the VAM periodicity pooled
# over every VRU (see the VamStatsRecorder docstring).
#

