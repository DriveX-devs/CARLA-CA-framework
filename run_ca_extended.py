# Track<->GT association category rules (see _associate_tracks_to_gt).
# Round 1 (preferred) matches within the same category; a pedestrian track may
# also claim a bike GT because a CARLA bicycle carries a rider YOLO can see as a
# lone person. Round 2 (compatible) allows only physically plausible category
# confusions -- crucially, a vehicle is NEVER matched to a lone pedestrian.
MATCH_PREFERRED = {
    'vehicle': ('vehicle',),
    'bike': ('bike',),
    'pedestrian': ('pedestrian', 'bike'),
}
MATCH_COMPATIBLE = {
    'vehicle': ('vehicle', 'bike'),
    'bike': ('bike', 'pedestrian', 'vehicle'),
    'pedestrian': ('pedestrian', 'bike'),
}


def _associate_tracks_to_gt(tracks, gt_states, eval_dist):
    """Associate confirmed tracks to ground-truth actors, one-to-one.

    Each GT actor is claimed by at most one track and each track by at most one
    GT actor, resolved greedily by ascending distance (the closest admissible
    track/GT pairs win). A first round matches within the same category
    (MATCH_PREFERRED); a second round, for still-unmatched tracks, allows only
    physically plausible category confusions (MATCH_COMPATIBLE) so a vehicle
    detection is never bound to a lone pedestrian. Returns
    ``{track_id: gt_dict or None}``.

    This replaces the former per-track nearest-GT search, which could (a) bind
    two different tracks to the *same* GT actor and (b) attach a vehicle track
    to an unrelated pedestrian through an unrestricted any-category fallback --
    both of which corrupt the track<->GT identity that the offline
    collision/GT alignment relies on.
    """
    result = {t.track_id: None for t in tracks}
    used_gt = set()
    for compat in (MATCH_PREFERRED, MATCH_COMPATIBLE):
        candidates = []
        for t in tracks:
            if result[t.track_id] is not None:
                continue
            gate = eval_dist[t.category]
            allowed = compat[t.category]
            for g in gt_states:
                if g['id'] in used_gt or g['category'] not in allowed:
                    continue
                d = float(np.linalg.norm(t.position[:2] - g['xy']))
                if d < gate:
                    candidates.append((d, t.track_id, g))
        candidates.sort(key=lambda c: c[0])
        assigned = set()
        for d, tid, g in candidates:
            if tid in assigned or g['id'] in used_gt:
                continue
            result[tid] = g
            assigned.add(tid)
            used_gt.add(g['id'])
    return result


